    execute format('alter table public.%I enable row level security', table_name);
    execute format('drop policy if exists staff_access on public.%I', table_name);
    execute format('create policy staff_access on public.%I for all to authenticated using (public.is_approved_staff()) with check (public.is_approved_staff())', table_name);
    execute format('grant select, insert, update, delete on public.%I to authenticated', table_name);
  end loop;
end $$;
