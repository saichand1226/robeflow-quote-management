create table if not exists public.quote_attachments (
  id bigint generated by default as identity primary key,
  quote_id bigint not null references public.quotes(id) on delete cascade,
  file_name text not null, content_type text not null default 'application/octet-stream', size bigint not null default 0,
  object_key text not null unique, created_at timestamptz not null default now()
);
create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  name text not null, company_name text not null default '', email text not null, phone text not null default '',
  address text not null default '', site_address text not null default '', project_type text not null default 'Wardrobes',
  areas text not null default '', preferred_colour text not null default '', timeframe text not null default '', notes text not null default '',
  status text not null default 'New', salesperson_name text not null default '', created_at timestamptz not null default now()
);
create table if not exists public.enquiry_attachments (
  id bigint generated by default as identity primary key,
  enquiry_id bigint not null references public.enquiries(id) on delete cascade,
  file_name text not null, content_type text not null default 'application/octet-stream', size bigint not null default 0,
  object_key text not null unique, created_at timestamptz not null default now()
);
create table if not exists public.job_schedule_events (
  id bigint generated by default as identity primary key,
  quote_id bigint not null references public.quotes(id) on delete cascade,
  event_type text not null check (event_type in ('Site measure','Installation')),
  scheduled_date date not null, start_time time not null, end_time time not null,
  assigned_to text not null default '', notes text not null default '', status text not null default 'Scheduled',
  created_at timestamptz not null default now()
);
create table if not exists public.pick_list_items (
  id bigint generated by default as identity primary key,
  quote_id bigint not null references public.quotes(id) on delete cascade,
  area_name text not null default '', product_name text not null, sku text not null default '',
  quantity numeric(12,2) not null default 0, unit_cost numeric(12,2) not null default 0,
  checked boolean not null default false, notes text not null default '', sort_order integer not null default 0,
  created_at timestamptz not null default now()
);
create table if not exists public.email_deliveries (
  id bigint generated by default as identity primary key,
  quote_id bigint references public.quotes(id) on delete cascade, kind text not null,
  recipient text not null, provider_id text, status text not null default 'Sent', error text,
  created_at timestamptz not null default now(), unique(kind, quote_id, recipient, provider_id)
);

